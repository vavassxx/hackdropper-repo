-- Целитель (6,4): интерактивный NPC с диалогом. Объясняет руны здоровья —
-- механикой заведует мировой хост (hud.lua), здесь только разговор.
entity.set_trigger(2.0)

entity.on_interact(function(player)
  engine.dialog(player,
    "Здравствуй, путник. Вижу, ты осваиваешься. Запомни главное: руны на земле лечат и калечат.",
    {"Что за руны?", "Расскажи про здоровье", "Спасибо, пойду"},
    function(choice)
      if choice == 1 then
        engine.dialog(player,
          "Светлая руна у лавки возвращает жизнь, пока стоишь на ней. Пылающая на юго-востоке, у старой стены, отнимает по единице за каждый миг.",
          {"Это всё?", "Понял, спасибо"},
          function(choice2)
            engine.notify(choice2 == 1
                and "Целитель: Всё просто. Не стой в огне — и будешь жить."
                or "Целитель кивает вам.")
          end)
      elseif choice == 2 then
        engine.dialog(player,
          "У каждого путника сто единиц жизни. Слева сверху — твоя полоса здоровья и число рядом: HP 100/100, например.",
          {"Увижу после первого шага"},
          function() engine.notify("Целитель: Вот теперь точно увидишь.") end)
      else
        engine.notify("Целитель: Будь осторожен на рунах. Возвращайся.")
      end
    end)
end)