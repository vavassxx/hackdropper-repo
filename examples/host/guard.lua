-- Страж у площади (10,7). Разговорчивый, но подозрительный.
entity.set_trigger(2.0)

entity.on_interact(function(player)
  engine.dialog(player,
    "Стой, кто идёт? Не каждый день вижу незнакомцев на этой площади.",
    {"Я друг Стражника города", "Просто мимо прохожу", "Отдавай свой мешок!"},
    function(choice)
      if choice == 1 then
        engine.dialog(player, "Хм, а значок городской у тебя есть?.. Шучу. Проходи. Привет от меня Старейшине!",
          {"Спасибо, страж!"},
          function() engine.notify("Страж козырнул вам.") end)
      elseif choice == 2 then
        engine.notify("Страж: Мимо здесь можно только по делам... но ладно, проходи. Глазами за тобой последишь.")
      else
        engine.notify("Страж: Вздумал грабить? Глаз да глаз! Запомнил я тебя, " .. player.name() .. ".")
      end
    end)
end)